"""Local, sequence-first interface for guide-detection probe design.

This file is maintained directly; it is not generated by nbdev.
"""
from importlib.resources import files
from pathlib import Path
from tempfile import TemporaryDirectory

import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st

from probeharbour.guide_plotting import guide_overview, plot_guide_candidates, write_guide_report
from probeharbour.guides import design_guides, guide_summary, top_guides
from probeharbour.thermo import ThermoParameters


def main():
    st.set_page_config(page_title="GuideHarbour", page_icon="🧬", layout="wide")
    st.title("GuideHarbour")
    st.markdown("Design detection probes across a **guide + scaffold** boundary, inspect their scores, and compare top alternatives.")
    st.caption("A separate adaptation of ProbeHarbour. These are detection probes for existing guides; scores do not measure CRISPR activity.")

    source = st.radio("Guide input", ["Included 15-guide example", "Upload CSV"], horizontal=True)
    if source == "Upload CSV":
        upload = st.file_uploader("CSV with guide_id, guide_sequence and scaffold_sequence", type=["csv"])
        if upload is None:
            st.info("Upload a CSV. Optional columns: prefix_sequence and transcribed_leader.")
            return
        try:
            frame = pd.read_csv(upload, keep_default_na=False, dtype=str)
        except (ValueError, pd.errors.ParserError) as exc:
            st.error(f"Cannot read this CSV: {exc}")
            return
    else:
        frame = pd.read_csv(files("probeharbour").joinpath("data/example_guides.csv"), keep_default_na=False, dtype=str)

    with st.form("guide_design"):
        st.subheader("Target sequences")
        edited = st.data_editor(frame, hide_index=True, num_rows="dynamic", width="stretch")
        st.caption("All sequences are sense 5′→3′. RNA mode excludes prefix_sequence and uses only an explicitly entered transcribed_leader.")
        left, middle, right = st.columns(3)
        chemistry = left.selectbox("Scoring rules", ["prime_5k", "xenium_v1"])
        target_label = middle.selectbox("Target sequence", ["RNA: leader + guide + scaffold", "Full construct: prefix + guide + scaffold"])
        boundary = right.selectbox("Boundary", ["guide_scaffold", "prefix_guide", "both"])
        left, middle, right = st.columns(3)
        arm_choice = left.selectbox("Length per arm", ["Chemistry default (16 / 20 nt)", "Custom"])
        arm_length = middle.number_input("Custom arm length (nt)", min_value=8, max_value=30, value=16, step=1)
        min_overlap = right.number_input("Minimum guide bases covered", min_value=1, max_value=60, value=15, step=1)
        left, middle, right = st.columns(3)
        slide_min = left.number_input("Minimum slide (nt)", min_value=-50, max_value=50, value=-5, step=1)
        slide_max = middle.number_input("Maximum slide (nt)", min_value=-50, max_value=50, value=5, step=1)
        min_mismatches = right.number_input("Minimum differences from another guide target", min_value=0, max_value=60, value=3, step=1)
        left, right = st.columns(2)
        min_score = left.number_input("Minimum chemistry score", min_value=0.0, max_value=1.0, value=0.0, step=0.05)
        top_n = right.number_input("Top alternatives per guide", min_value=1, max_value=20, value=3, step=1)
        require_qc = st.checkbox("Require every inherited chemistry QC rule to pass", value=False,
                                 help="By default, chemistry modifiers reduce the score. This option makes each active modifier an exclusion.")
        with st.expander("Thermodynamic parameters"):
            st.caption("Defaults are inherited from this version of ProbeHarbour. They are not a validated guide-RNA assay calibration.")
            a, b, c, d = st.columns(4)
            mv = a.number_input("Monovalent salts (mM)", min_value=0.0, value=80.0)
            dv = b.number_input("Divalent salts (mM)", min_value=0.0, value=5.0)
            dntp = c.number_input("dNTPs (mM)", min_value=0.0, value=0.0)
            dna = d.number_input("DNA concentration (nM)", min_value=0.01, value=1500.0)
        submitted = st.form_submit_button("Design and rank probes", type="primary")

    if submitted:
        if slide_min > slide_max:
            st.error("Minimum slide must be less than or equal to maximum slide.")
            return
        parameters = ThermoParameters(mv_conc=mv, dv_conc=dv, dntp_conc=dntp, dna_conc=dna)
        try:
            with st.spinner("Scoring candidates and comparing guide targets…"):
                result = design_guides(
                    edited, chemistry=chemistry,
                    target_mode="rna" if target_label.startswith("RNA:") else "full_construct",
                    boundary=boundary, arm_length=None if arm_choice.startswith("Chemistry") else int(arm_length),
                    slides=range(int(slide_min), int(slide_max) + 1),
                    min_guide_overlap=int(min_overlap), min_panel_mismatches=int(min_mismatches),
                    min_score=float(min_score), require_qc_pass=require_qc, parameters=parameters,
                )
            st.session_state.guide_result = result
            st.session_state.guide_top_n = int(top_n)
        except (ValueError, RuntimeError, KeyError) as exc:
            st.session_state.pop("guide_result", None)
            st.error(str(exc))
            return

    if "guide_result" not in st.session_state:
        st.info("The 15 supplied guides are ready. Select Design and rank probes to generate results.")
        return

    result = st.session_state.guide_result
    n = st.session_state.guide_top_n
    summary = guide_summary(result)
    top = top_guides(result, n=n)
    st.divider()
    st.subheader("Results")
    st.caption("Results use the last submitted settings. Edit the form and run again to update them.")
    a, b, c = st.columns(3)
    a.metric("Guides", len(summary))
    b.metric("Candidates scored", len(result.obs))
    c.metric("Top alternatives shown", len(top))
    st.info("Specificity here is an ungapped sequence comparison within the supplied guide set. Transcriptome matches and RNA accessibility have not been assessed. Top probes for a guide are overlapping alternatives.")
    fig = guide_overview(result, n=n)
    st.pyplot(fig)
    plt.close(fig)
    st.dataframe(summary, hide_index=True, width="stretch")
    if len(summary):
        guide_id = st.selectbox("Inspect a guide", summary["guide_id"].tolist())
        fig = plot_guide_candidates(result, guide_id, n=n)
        st.pyplot(fig)
        plt.close(fig)
        st.dataframe(top.loc[top["guide_id"].eq(guide_id)], hide_index=True, width="stretch")
    with st.expander("All candidates and exclusion reasons"):
        st.dataframe(result.obs, hide_index=True, width="stretch")
    with st.expander("Run settings and provenance"):
        st.json(result.metadata)

    a, b, c = st.columns(3)
    a.download_button("Download all candidates", result.obs.to_csv(index=False), "candidates.csv", "text/csv")
    b.download_button("Download top alternatives", top.to_csv(index=False), "top_candidates.csv", "text/csv")
    with TemporaryDirectory() as temporary:
        report_path = Path(temporary) / "guide_report.html"
        write_guide_report(result, report_path, n=n)
        c.download_button("Download interactive report", report_path.read_bytes(), "guide_report.html", "text/html")


if __name__ == "__main__":
    main()
